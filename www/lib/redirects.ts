// Redirects from the API URLs of the original Fresh site to the TypeDoc pages.
//
// The old site addressed symbols as `/api/mod.ts~Lens` and members as
// `/api/mod.ts~Lens.prototype.find` (instance) or `/api/mod.ts~Lens.find`
// (static). Netlify can't split a path segment at `~`, so every known URL gets
// its own rule in `dist/_redirects`. Other old URLs of a module (private
// members, non-exported types) fall back to the module's page through the
// rules in netlify.toml, which Netlify applies after `_redirects`.

export interface ApiSymbol {
  /** Module (entry point) the symbol is exported from, e.g. `mod`. */
  module: string;
  /** Exported symbol name, e.g. `Lens`. */
  name: string;
  /** URL of the symbol's TypeDoc page, e.g. `/api/mod/Lens/`. Re-exported
   * symbols are documented in another module. */
  page: string;
  /** Member names that have an anchor on the symbol's page. */
  members: string[];
}

export interface Redirect {
  from: string;
  to: string;
}

export function legacyApiRedirects(modules: string[], symbols: ApiSymbol[]): Redirect[] {
  const redirects: Redirect[] = [];
  for (const module of modules) {
    redirects.push({ from: `/api/${module}.ts`, to: `/api/${module}/` });
  }
  for (const { module, name, page, members } of symbols) {
    const old = `/api/${module}.ts~${name}`;
    redirects.push({ from: old, to: page });
    for (const member of members) {
      // TypeDoc anchors are lowercased member names.
      const to = `${page}#${member.toLowerCase()}`;
      redirects.push({ from: `${old}.prototype.${member}`, to });
      redirects.push({ from: `${old}.${member}`, to });
    }
  }
  return redirects;
}

/** Formats redirects in Netlify's `_redirects` file syntax. */
export function formatRedirects(redirects: Redirect[]): string {
  const header =
    "# Generated by www/site-plugin.ts: old API URLs of the original site.\n" +
    "# Netlify applies the first matching rule.\n";
  const width = Math.max(...redirects.map((r) => r.from.length));
  const lines = redirects.map((r) => `${r.from.padEnd(width)}  ${r.to}  301`);
  return `${header}${lines.join("\n")}\n`;
}
